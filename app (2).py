import gradio as gr
from skimage.metrics import structural_similarity
import imutils
import cv2
import numpy as np
from PIL import Image
import requests

# Charger une image PAN originale (référence)
url = "https://www.thestatesman.com/wp-content/uploads/2019/07/pan-card.jpg"
original = Image.open(requests.get(url, stream=True).raw).resize((250, 160))
original = np.array(original)

# Fonction principale
def detect_pan_tampering(uploaded_image):
    try:
        # Convertir image utilisateur
        tampered = cv2.resize(uploaded_image, (250, 160))

        # Niveaux de gris
        original_gray = cv2.cvtColor(original, cv2.COLOR_BGR2GRAY)
        tampered_gray = cv2.cvtColor(tampered, cv2.COLOR_BGR2GRAY)

        # SSIM
        (score, diff) = structural_similarity(original_gray, tampered_gray, full=True)
        diff = (diff * 255).astype("uint8")

        # Threshold + contours
        thresh = cv2.threshold(diff, 0, 255,
                               cv2.THRESH_BINARY_INV | cv2.THRESH_OTSU)[1]

        cnts = cv2.findContours(thresh.copy(),
                                cv2.RETR_EXTERNAL,
                                cv2.CHAIN_APPROX_SIMPLE)
        cnts = imutils.grab_contours(cnts)

        original_copy = original.copy()
        tampered_copy = tampered.copy()

        for c in cnts:
            (x, y, w, h) = cv2.boundingRect(c)
            cv2.rectangle(original_copy, (x, y), (x + w, y + h), (0, 0, 255), 2)
            cv2.rectangle(tampered_copy, (x, y), (x + w, y + h), (0, 0, 255), 2)

        # Résultat texte
        if score < 0.90:
            result = f"⚠️ Carte potentiellement falsifiée (SSIM: {score:.2f})"
        else:
            result = f"✅ Carte probablement authentique (SSIM: {score:.2f})"

        return result, original_copy, tampered_copy, diff, thresh

    except Exception as e:
        return f"Erreur: {str(e)}", None, None, None, None

# Interface Gradio
interface = gr.Interface(
    fn=detect_pan_tampering,
    inputs=gr.Image(type="numpy", label="Uploader une carte PAN"),
    outputs=[
        gr.Textbox(label="Résultat"),
        gr.Image(label="Image originale avec contours"),
        gr.Image(label="Image analysée avec contours"),
        gr.Image(label="Image de différence"),
        gr.Image(label="Image seuillée")
    ],
    title="Détection de falsification de carte PAN (SSIM)",
    description="Compare une carte PAN avec une image de référence pour détecter les modifications."
)

# Lancer
if __name__ == "__main__":
    interface.launch()